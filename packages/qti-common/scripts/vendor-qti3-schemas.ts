/**
 * Vendor the QTI 3.0 schemas under `schemas/qti3/` from a local checkout of
 * 1EdTech's `qti-documentation` repository (`qti-v3p0/Final Release/xsds`).
 *
 * The roots are the ASI schema and the QTI 3 content-packaging profile. Three
 * transformations make them usable offline and small enough to commit:
 *
 * 1. **Annotations are stripped**, except the first one in each file, which carries the
 *    1EdTech IPR and distribution notice. The ASI schema is 19 MB with them and ~0.6 MB
 *    without; libxml2 ignores them either way.
 * 2. **`schemaLocation` is rewritten to a flat local basename**, for the same reason as
 *    `packages/to-pie/schemas/qti`: libxml2 resolves it literally, and the wasm sandbox
 *    has no network.
 * 3. **MathML 3 and SSML 1.1 resolve to skip-content stubs.** The copies vendored for
 *    QTI 2.2 use IMS's modified namespaces (`2010/Math/MathML`, `2010/10/synthesis`),
 *    which QTI 3 does not import. The stubs declare exactly the elements the ASI schema
 *    references and accept any content inside them: embedded MathML and SSML go
 *    unchecked, everything else is judged against the official schema.
 *
 * `xml.xsd`, `XInclude.xsd` and the xlink schema are copied from `packages/to-pie`, the
 * IEEE LOM loose binding from the pie-to-qti2 IMS CP fixtures.
 *
 * Run: `bun run packages/qti-common/scripts/vendor-qti3-schemas.ts <qti-documentation>/qti-v3p0/Final\ Release/xsds`
 */
import * as fs from 'node:fs';
import * as path from 'node:path';

const sourceDir = process.argv[2];
if (!sourceDir) {
  throw new Error('usage: vendor-qti3-schemas.ts <qti-v3p0 xsds dir>');
}

const PACKAGES = path.join(import.meta.dirname, '..', '..');
const OUT_DIR = path.join(import.meta.dirname, '..', 'schemas', 'qti3');

/** The roots and everything they import from the 1EdTech release. */
const UPSTREAM = [
  'imsqti_asiv3p0_v1p0.xsd',
  'imsqtiv3p0_imscpv1p2_v1p0.xsd',
  'imsqtiv3p0_csmv1p1_v1p0.xsd',
  'imsqti_metadatav3p0_v1p0.xsd',
  'imsqtiv3p0_cpextv1p2_v1p0.xsd',
  'imsqtiv3p0_afa3p0drd_v1p0.xsd',
];

/** Imports the release does not ship, copied verbatim from elsewhere in the repo. */
const COPIED: ReadonlyArray<readonly [string, string]> = [
  ['xml.xsd', path.join(PACKAGES, 'to-pie', 'schemas', 'qti', 'xml.xsd')],
  ['XInclude.xsd', path.join(PACKAGES, 'to-pie', 'schemas', 'qti', 'XInclude.xsd')],
  ['xlink.xsd', path.join(PACKAGES, 'to-pie', 'schemas', 'qti', 'xlink-href.xsd')],
  [
    'imsmd_loose_v1p3p2.xsd',
    path.join(PACKAGES, 'pie-to-qti2', 'tests', 'fixtures', 'schemas', 'imscp', 'imsmd_loose_v1p3p2.xsd'),
  ],
];

const SSML_ELEMENTS = [
  'audio',
  'break',
  'emphasis',
  'mark',
  'p',
  'phoneme',
  'prosody',
  's',
  'say-as',
  'speak',
  'sub',
  'voice',
];

function stub(namespace: string, elements: readonly string[], source: string): string {
  const decls = elements
    .map(
      (name) =>
        `  <xs:element name="${name}">\n` +
        '    <xs:complexType mixed="true">\n' +
        '      <xs:sequence>\n' +
        '        <xs:any namespace="##any" processContents="skip" minOccurs="0" maxOccurs="unbounded"/>\n' +
        '      </xs:sequence>\n' +
        '      <xs:anyAttribute namespace="##any" processContents="skip"/>\n' +
        '    </xs:complexType>\n' +
        '  </xs:element>\n'
    )
    .join('');
  return (
    '<?xml version="1.0" encoding="UTF-8"?>\n' +
    `<!-- Stub for ${source}: declares the elements the QTI 3.0 ASI schema references and skips their content. Generated by packages/qti-common/scripts/vendor-qti3-schemas.ts. -->\n` +
    `<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema" targetNamespace="${namespace}" elementFormDefault="qualified">\n` +
    decls +
    '</xs:schema>\n'
  );
}

function transform(xsd: string): string {
  let kept = false;
  return xsd
    .replace(/[ \t]*<xs:annotation>[\s\S]*?<\/xs:annotation>[ \t]*\r?\n?/g, (block) => {
      if (kept) {
        return '';
      }
      kept = true;
      return block;
    })
    .replace(/schemaLocation\s*=\s*"([^"]+)"/g, (_m, location: string) => {
      return `schemaLocation="${path.posix.basename(location)}"`;
    });
}

fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });

for (const name of UPSTREAM) {
  const xsd = fs.readFileSync(path.join(sourceDir, name), 'utf8');
  fs.writeFileSync(path.join(OUT_DIR, name), transform(xsd));
}
for (const [name, from] of COPIED) {
  fs.copyFileSync(from, path.join(OUT_DIR, name));
}
fs.writeFileSync(
  path.join(OUT_DIR, 'mathml3.xsd'),
  stub('http://www.w3.org/1998/Math/MathML', ['math'], 'MathML 3')
);
fs.writeFileSync(
  path.join(OUT_DIR, 'ssmlv1p1-core.xsd'),
  stub('http://www.w3.org/2001/10/synthesis', SSML_ELEMENTS, 'SSML 1.1')
);

// Every import must now resolve to a file in the directory.
const written = new Set(fs.readdirSync(OUT_DIR));
for (const name of written) {
  const xsd = fs.readFileSync(path.join(OUT_DIR, name), 'utf8');
  for (const match of xsd.matchAll(/<xs:(?:import|include)[^>]*schemaLocation="([^"]+)"/g)) {
    if (!written.has(match[1] as string)) {
      throw new Error(`${name} imports ${match[1]}, which is not vendored`);
    }
  }
}
console.log(`Wrote ${written.size} schemas to ${path.relative(process.cwd(), OUT_DIR)}`);
